"""Training entrypoint.

Run as `python -m leafcheck.train --config configs/smoke.yaml` (CI) or
`python -m leafcheck.train --config configs/train.yaml` (real data on GPU).

Outputs (under output_dir):
- model.pt            : model state_dict
- class_names.json     : ordered list of class names (used by serving)
- metrics.json        : per-epoch + final metrics, hardware, training time
- config_snapshot.yaml: exact config used (in case the YAML drifts later)

The smoke config trains on a deterministic synthetic dataset generated by
`leafcheck.synth_data`. The full config reads `data/manifest.csv` from M2.
"""

from __future__ import annotations

import argparse
import json
import platform
import random
import sys
import time
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
import yaml
from PIL import Image
from torch.utils.data import DataLoader, Dataset

from leafcheck import preprocess as pp
from leafcheck.model import build_model, class_imbalance_ratio

# ---------- dataset ----------


class ManifestDataset(Dataset):
    """Dataset that reads images from a manifest.csv produced by M2.

    Expected columns: path, class, group_id, split, sha256.
    """

    def __init__(self, manifest_csv: Path, split: str, class_to_idx: dict[str, int]) -> None:
        import csv

        self.items: list[tuple[Path, int]] = []
        with manifest_csv.open() as fh:
            for row in csv.DictReader(fh):
                if row["split"] != split:
                    continue
                cls = row["class"]
                if cls not in class_to_idx:
                    continue
                self.items.append((Path(row["path"]), class_to_idx[cls]))
        self.split = split

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        path, label = self.items[idx]
        img = Image.open(path)
        return img, label


class SyntheticDataset(Dataset):
    """Deterministic synthetic dataset for the smoke config.

    Generates `per_class[i]` images for class `i` on the fly. Re-runs with
    the same seed produce identical images.

    To create an imbalanced dataset, pass a `per_class` list with varying
    counts (e.g. [1, 4, 4, 16]) — used to test the weighted-loss branch.
    """

    def __init__(
        self,
        *,
        n_classes: int,
        per_class: int | list[int],
        seed: int,
        size: tuple[int, int] = (96, 96),
    ) -> None:
        from leafcheck.synth_data import _GENERATORS  # noqa: PLC0415

        if isinstance(per_class, int):
            per_class_list = [per_class] * n_classes
        else:
            if len(per_class) != n_classes:
                raise ValueError(f"per_class has {len(per_class)} entries; expected {n_classes}")
            per_class_list = list(per_class)
        self.n_classes = n_classes
        self.items: list[tuple[Image.Image, int]] = []
        # Curated order so the first 6 are mutually distinct: 3 gradients
        # then 3 solids. The alphabetical sort of _GENERATORS would put
        # the two blob_* generators first, which are too similar for the
        # model to discriminate reliably. See DECISIONS.md D8.
        names = ["gradient_1", "gradient_2", "gradient_3",
                 "solid_a", "solid_b", "solid_c"][:n_classes]
        for cls_idx, name in enumerate(names):
            gen = _GENERATORS[name]
            for sample in range(per_class_list[cls_idx]):
                img = _deterministic_variation(gen, seed + cls_idx * 1000 + sample)
                img = img.resize(size, Image.BILINEAR)
                self.items.append((img, cls_idx))

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        img, label = self.items[idx]
        return img, label


def _deterministic_variation(gen, seed: int) -> Image.Image:
    """Call a generator but with a per-call seed override if possible.

    The synth_data functions use a hardcoded seed internally. We work around
    this by using the global RNG seeded with `seed` so each call produces
    a different but reproducible image.
    """
    import random as _random

    _random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    img = gen()
    # Reset global seed to a known value so the next call also gets a
    # deterministic image. (Tests assert the same metrics across two runs.)
    _random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    return img


# ---------- training loop ----------


def _collate(batch: list[tuple[Image.Image, int]]) -> tuple[torch.Tensor, torch.Tensor]:
    imgs = [b[0] for b in batch]
    labels = [b[1] for b in batch]
    # Pre-process the WHOLE batch through the same module the rest of the
    # codebase uses (G2). Augmentation is on for training, off for eval.
    x = pp.preprocess_batch(imgs, augment=True)
    y = torch.tensor(labels, dtype=torch.long)
    return x, y


def _set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def _hardware_info() -> dict[str, str]:
    info: dict[str, str] = {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "torch": torch.__version__,
    }
    info["device"] = "cuda" if torch.cuda.is_available() else "cpu"
    if torch.cuda.is_available():
        info["cuda_device"] = torch.cuda.get_device_name(0)
    return info


def train(config: dict[str, Any]) -> dict[str, Any]:
    """Run a single training run end-to-end. Returns the metrics dict."""
    seed = int(config["seed"])
    _set_seed(seed)

    image_size = int(config.get("image_size", 224))
    epochs = int(config["epochs"])
    batch_size = int(config["batch_size"])
    lr = float(config["lr"])
    opt_name = config.get("optimizer", "sgd").lower()
    momentum = float(config.get("momentum", 0.9))
    weight_decay = float(config.get("weight_decay", 1e-4))
    early_stop_patience = int(config.get("early_stop_patience", 3))
    imbalance_threshold = float(config.get("imbalance_threshold", 3.0))
    pretrained = bool(config.get("pretrained", True))
    device_str = config.get("device", "cpu")
    output_dir = Path(config["output_dir"])
    output_dir.mkdir(parents=True, exist_ok=True)

    # Build dataset.
    if "synth_classes" in config:
        # Smoke config — no real data needed.
        n_classes = int(config["synth_classes"])
        per_class_cfg = config.get("synth_per_class", 24)
        if isinstance(per_class_cfg, list):
            per_class = per_class_cfg
        else:
            per_class = int(per_class_cfg)
        ds = SyntheticDataset(
            n_classes=n_classes, per_class=per_class, seed=seed, size=(image_size, image_size)
        )
        class_names = [f"class_{i}" for i in range(n_classes)]
        train_size = int(len(ds) * 0.7)
        val_size = len(ds) - train_size
        train_ds, val_ds = torch.utils.data.random_split(ds, [train_size, val_size])
        train_source = "synthetic"
    else:
        # Full config — read manifest.csv from M2.
        manifest_path = Path(config["data_root"])
        class_names = _read_class_names(manifest_path)
        class_to_idx = {c: i for i, c in enumerate(class_names)}
        train_ds = ManifestDataset(manifest_path, "train", class_to_idx)
        val_ds = ManifestDataset(manifest_path, "val", class_to_idx)
        train_source = "manifest"

    train_loader = DataLoader(
        train_ds, batch_size=batch_size, shuffle=True, collate_fn=_collate, num_workers=0
    )
    val_loader = DataLoader(
        val_ds, batch_size=batch_size, shuffle=False, collate_fn=_collate, num_workers=0
    )

    # Class imbalance → weighted CE.
    n_classes_actual = len(class_names) if class_names else int(config["synth_classes"])
    train_class_counts = _count_classes_in_loader(train_loader, n_classes_actual)
    imbalance = class_imbalance_ratio(train_class_counts)
    use_weighted = imbalance > imbalance_threshold
    if use_weighted:
        weights = torch.tensor([1.0 / max(1, c) for c in train_class_counts], dtype=torch.float)
        weights = weights / weights.sum() * len(weights)  # normalize
        criterion = nn.CrossEntropyLoss(weight=weights)
    else:
        criterion = nn.CrossEntropyLoss()

    model = build_model(n_classes_actual, pretrained=pretrained)
    model.eval()  # ensures BatchNorm stays in eval mode at inference
    device = torch.device(device_str)
    model.to(device)
    if opt_name == "adam":
        optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=weight_decay)
    else:
        optimizer = optim.SGD(
            model.parameters(), lr=lr, momentum=momentum, weight_decay=weight_decay
        )

    # Train + early stop.
    history: list[dict[str, float]] = []
    best_val_f1 = -1.0
    patience_left = early_stop_patience
    started = time.time()
    for epoch in range(epochs):
        model.train()
        loss_sum = 0.0
        n = 0
        for x, y in train_loader:
            x = x.to(device)
            y = y.to(device)
            optimizer.zero_grad()
            logits = model(x)
            loss = criterion(logits, y)
            loss.backward()
            optimizer.step()
            loss_sum += float(loss.item()) * y.size(0)
            n += y.size(0)
        train_loss = loss_sum / max(1, n)

        model.eval()
        with torch.inference_mode():
            all_preds: list[int] = []
            all_labels: list[int] = []
            for x, y in val_loader:
                x = x.to(device)
                logits = model(x)
                preds = logits.argmax(dim=1).cpu().tolist()
                all_preds.extend(preds)
                all_labels.extend(y.tolist())
        from sklearn.metrics import f1_score  # noqa: PLC0415

        val_f1 = float(f1_score(all_labels, all_preds, average="macro", zero_division=0))
        val_acc = float(
            sum(int(p == y) for p, y in zip(all_preds, all_labels, strict=False))
            / max(1, len(all_labels))
        )
        history.append(
            {"epoch": epoch, "train_loss": train_loss, "val_macro_f1": val_f1, "val_acc": val_acc}
        )
        if val_f1 > best_val_f1:
            best_val_f1 = val_f1
            patience_left = early_stop_patience
        else:
            patience_left -= 1
            if patience_left <= 0:
                break

    elapsed = time.time() - started
    model.eval()
    final_metrics = {
        "history": history,
        "best_val_macro_f1": best_val_f1,
        "elapsed_seconds": elapsed,
        "imbalance_ratio": imbalance,
        "weighted_loss_used": use_weighted,
        "class_count": len(train_class_counts),
        "train_class_counts": train_class_counts,
        "image_size": image_size,
        "hardware": _hardware_info(),
        "config_path": str(config.get("_config_path", "")),
        "train_source": train_source,
        "device": device_str,
    }

    # Save artifacts.
    torch.save(model.state_dict(), output_dir / "model.pt")
    (output_dir / "class_names.json").write_text(json.dumps(class_names, indent=2))
    (output_dir / "metrics.json").write_text(json.dumps(final_metrics, indent=2))
    (output_dir / "config_snapshot.yaml").write_text(
        yaml.safe_dump({k: v for k, v in config.items() if k != "_config_path"})
    )
    return final_metrics


def _count_classes_in_loader(loader: DataLoader, n_classes: int) -> list[int]:
    counts: Counter[int] = Counter()
    for _, y in loader:
        for label in y.tolist():
            counts[label] += 1
    return [counts.get(i, 0) for i in range(n_classes)]


def _read_class_names(manifest_path: Path) -> list[str]:
    import csv

    classes: set[str] = set()
    with manifest_path.open() as fh:
        for row in csv.DictReader(fh):
            classes.add(row["class"])
    return sorted(classes)


def _load_config(path: Path) -> dict[str, Any]:
    cfg = yaml.safe_load(path.read_text()) or {}
    cfg["_config_path"] = str(path)
    return cfg


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="leafcheck.train")
    p.add_argument("--config", required=True, type=Path)
    return p


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    metrics = train(_load_config(args.config))
    print(
        json.dumps(
            {
                "best_val_macro_f1": metrics["best_val_macro_f1"],
                "elapsed_seconds": metrics["elapsed_seconds"],
                "epochs_completed": len(metrics["history"]),
                "weighted_loss_used": metrics["weighted_loss_used"],
                "imbalance_ratio": metrics["imbalance_ratio"],
                "train_source": metrics["train_source"],
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
